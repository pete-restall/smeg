const _: () = {
    assert!(
        size_of::<IsrVectorTable>() == (85 * 4) + size_of::<CortexM4IsrVectorTable>(),
        "There must be 85 ISR vectors for the STM32L432KC, each 32-bits");

    assert!(align_of::<IsrVectorTable>() == 4, "Alignment of the ISR vector table must be 32-bits");
};

