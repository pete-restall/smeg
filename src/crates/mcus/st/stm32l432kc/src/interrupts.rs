#[macro_export]
macro_rules! define_isr_vector_table_from {
    ($isrs:expr) => {
        #[used]
        #[unsafe(link_section = ".smeg.isr_vector_table.st.stm32l432kc")]
        static _ISR_VECTOR_TABLE: $crate::interrupts::IsrVectorTable = const { $isrs }.with_default_unhandled();
    }
}
